#!/bin/sh
# build.sh builds libgifttypst for every platform package typst/embedded
# carries and puts the libraries there, compressed, with the Go files that
# embed them. Run it after a change to the crate and commit what it writes:
#
#	typst/ffi/build.sh
#
# It needs rustup, which installs the toolchain pinned in rust-toolchain.toml,
# and zig with cargo-zigbuild, which link the Linux libraries on any host.
# With Homebrew:
#
#	brew install rustup zig cargo-zigbuild
#	PATH="$(brew --prefix rustup)/bin:$PATH" typst/ffi/build.sh
#
# The macOS library is built only on a Mac. The Linux libraries are linked
# against glibc 2.28, so that they load on Debian 10, Ubuntu 20.04, RHEL 8
# and every later release, and on every Raspberry Pi OS of 64 bits.
set -eu
cd "$(dirname "$0")"
out=../embedded

if ! command -v rustup >/dev/null; then
	echo "build.sh: rustup is not on PATH; see the comment at the top" >&2
	exit 1
fi

# embed compresses the library $1 for the platform $2/$3 into the package
# and writes the Go file that embeds it there and only there.
embed() {
	lib=$1 goos=$2 goarch=$3
	name=$(basename "$lib")
	blob=${name%.*}_${goos}_${goarch}.${name##*.}.gz
	size=$(wc -c <"$lib" | tr -d ' ')
	sum=$( (sha256sum "$lib" 2>/dev/null || shasum -a 256 "$lib") | cut -d ' ' -f 1)
	gzip -9 -n -c "$lib" >"$out/$blob"
	{
		printf '// Code generated by typst/ffi/build.sh. DO NOT EDIT.\n\n'
		printf 'package embedded\n\nimport _ "embed"\n\n'
		printf '//go:embed %s\nvar blob []byte\n\n' "$blob"
		printf 'const (\n\tname = "%s"\n\tsize = %s\n\tsum  = "%s"\n)\n' "$name" "$size" "$sum"
	} >"$out/lib_${goos}_${goarch}.go"
	echo "$blob: $size bytes, $(wc -c <"$out/$blob" | tr -d ' ') compressed"
}

if [ "$(uname -s)" = Darwin ]; then
	MACOSX_DEPLOYMENT_TARGET=11.0 cargo build --release --locked --target aarch64-apple-darwin
	embed target/aarch64-apple-darwin/release/libgifttypst.dylib darwin arm64
fi
cargo zigbuild --release --locked --target aarch64-unknown-linux-gnu.2.28
embed target/aarch64-unknown-linux-gnu/release/libgifttypst.so linux arm64
cargo zigbuild --release --locked --target x86_64-unknown-linux-gnu.2.28
embed target/x86_64-unknown-linux-gnu/release/libgifttypst.so linux amd64
